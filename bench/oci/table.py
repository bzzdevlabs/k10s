#!/usr/bin/env python3
"""The checked-in syscall evidence and the k10-lx plan table.

  table.py collect     target/oci/runs/*.json (trace.py, elfscan.py) -> bench/oci/syscalls.json
  table.py render      bench/oci/syscalls.json + lxplan.py -> bench/oci/syscalls.md and the generated part of docs/LX.md
  table.py --check     render in memory; fails when the files differ or an M1 corpus image makes a call the plan
                       does not cover (cheap: no image, no guest)
"""
import collections
import json
import os
import re
import sys

import linuxabi as L
import lxplan
import oci

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
EVIDENCE = os.path.join(HERE, "syscalls.json")
TABLE = os.path.join(HERE, "syscalls.md")
LXMD = os.path.join(ROOT, "docs", "LX.md")
MARK = "<!-- {} generated by bench/oci/table.py: {} -->"
SHORT = {"alpine-sh": "sh", "nginx": "ngx", "redis": "rds", "python-http": "py", "node-http": "node",
         "temurin-jwebserver": "jvm", "postgres": "pg", "go-static": "go", "rust-static": "rs"}


def driver_line(d):
    """A driver step without timings or pids (stable across runs)."""
    d = re.sub(r" \[\d+ ms\]", "", d)
    d = re.sub(r"kill\(\d+, (\d+)\) = 0", "sent", d)
    step, _, res = d.partition(": ")
    return f"{step[:60]}{'...' if len(step) > 60 else ''}: {res[:60]}"


def collect():
    corpus = json.load(open(os.path.join(HERE, "corpus.json")))
    runs = os.path.join(oci.CACHE, "runs")
    out = {"images": {}, "syscalls": {}, "paths": {}, "signals": {}}
    for e in corpus:
        n = e["name"]
        t = json.load(open(os.path.join(runs, n + ".json")))
        s = json.load(open(os.path.join(runs, n + ".static.json")))
        progs = t["programs"]
        calls = collections.defaultdict(lambda: {"n": 0, "err": collections.Counter(), "args": collections.Counter()})
        paths, signals = collections.Counter(), collections.Counter()
        for p in progs.values():
            for nr, st in p["syscalls"].items():
                name = L.SYSCALLS.get(int(nr), f"nr{nr}")
                c = calls[name]
                c["n"] += st["n"]
                c["err"].update({L.ERRNO.get(int(k), k): v for k, v in st["err"].items()})
                c["args"].update({L.decode(name, k): v for k, v in st["args"].items()})
                paths.update({f"{name} {k}": v for k, v in st["paths"].items()})
            signals.update({L.signame(int(k)): v for k, v in p["signals"].items()})
        out["images"][n] = {
            "tag": e["tag"], "image": e["image"], "manifest": t["manifest"], "milestone": e.get("milestone", "M1"),
            "workload": e["workload"],
            "kernel": t["uname"], "layers_bytes": t["layers_bytes"], "exit": t["exit"], "killed": t["killed"],
            "driver": [driver_line(d) for d in t["driver"]],
            "programs": sorted(progs), "execs": sum(p["execs"] for p in progs.values()),
            "forks": sum(p["forks"] for p in progs.values()), "threads": sum(p["threads"] for p in progs.values()),
            "traced": sorted(calls), "static_closure": sorted(s["closure"]), "static_all": sorted(s["all"]),
            "inline": sorted(s["inline"]), "static_programs": s["static_programs"], "elf_objects": s["objects"],
            "closure_objects": s["closure_objects"],
        }
        for name, c in calls.items():
            out["syscalls"].setdefault(name, {})[n] = {"n": c["n"], "err": dict(sorted(c["err"].items())),
                                                       "args": dict(sorted(c["args"].items()))}
        out["paths"][n] = dict(sorted(paths.items()))
        out["signals"][n] = dict(sorted(signals.items()))
    json.dump(out, open(EVIDENCE, "w"), indent=1, sort_keys=True)
    open(EVIDENCE, "a").write("\n")


def plan_problems(ev):
    bad = []
    for name, per in sorted(ev["syscalls"].items(), key=lambda kv: L.NR.get(kv[0], 999)):
        m1 = [i for i in per if ev["images"][i]["milestone"] == "M1"]
        st, note = lxplan.status(name)
        if m1 and not (st in (lxplan.M1, lxplan.STUB, lxplan.REFUSED) or note.startswith("M1:")):
            bad.append(f"{name} ({st}) is used by M1 images {', '.join(m1)}")
    return bad


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |" for r in rows]
    return "\n".join(out)


def render(ev):
    imgs = list(ev["images"])
    im = ev["images"]
    m1 = [i for i in imgs if im[i]["milestone"] == "M1"]
    union = set(ev["syscalls"])
    union_m1 = {s for s, per in ev["syscalls"].items() if any(i in m1 for i in per)}
    closure = set().union(*(set(im[i]["static_closure"]) | set(im[i]["inline"]) for i in imgs))
    allref = set().union(*(set(im[i]["static_all"]) for i in imgs))
    kernel = sorted({im[i]["kernel"] for i in imgs})
    md = ["# Syscall evidence of the OCI corpus", "",
          "Generated by `bench/oci/table.py` from `syscalls.json` (`bench/oci/trace.sh` reproduces both). Traced:",
          f"lxtrace (ptrace) under {', '.join(kernel)} in QEMU/KVM, each image's own entrypoint and command with a",
          "realistic workload (start, requests, graceful stop by the image's stop signal), every process and thread",
          "of the container followed. Static: undefined dynamic symbols that are syscall wrappers in the traced",
          "programs and their DT_NEEDED closure (closure) and in every ELF object of the image (all, dlopen'd",
          "modules included; libc itself excluded), plus `mov $nr,%eax; syscall` sites in static binaries.",
          "The plan column is `bench/oci/lxplan.py` (docs/LX.md).", "",
          "## Images", ""]
    rows = []
    for i in imgs:
        x = im[i]
        rows.append([f"{i} (`{SHORT[i]}`)", f"`{x['tag']}`", x["milestone"], len(x["programs"]), x["execs"],
                     x["forks"], x["threads"], len(x["traced"]), len(set(x["static_closure"]) | set(x["inline"])),
                     len(x["static_all"]), x["exit"]])
    md.append(md_table(["image", "tag", "milestone", "programs", "execs", "forks", "threads", "traced calls",
                        "static closure (imports, inline)", "static all (imports)", "exit"], rows))
    md += ["", f"Union of traced calls: **{len(union)}** (M1 images: **{len(union_m1)}**); static closure union "
               f"{len(closure)}, static union over every ELF object {len(allref)}; x86-64 table: {len(L.SYSCALLS)}.",
           "", "Workloads (driver steps as run):", ""]
    for i in imgs:
        md.append(f"- {i}: " + ("; ".join(d.replace("|", "/") for d in im[i]["driver"]) or "the entrypoint script "
                                "runs to completion"))
    md += ["", "Image digests (index or manifest as pinned; amd64 manifest traced):", ""]
    for i in imgs:
        md.append(f"- {i}: `{im[i]['image']}` (manifest `{im[i]['manifest']}`)")
    md += ["", "## Calls", "", "Per image: calls traced (`s` = referenced statically only, in the closure).", ""]
    rows = []
    names = sorted(union | closure, key=lambda n: L.NR.get(n, 999))
    for n in names:
        per = ev["syscalls"].get(n, {})
        cells = []
        for i in imgs:
            if i in per:
                cells.append(per[i]["n"])
            elif n in im[i]["static_closure"] or n in im[i]["inline"]:
                cells.append("s")
            else:
                cells.append("")
        errs = collections.Counter()
        for v in per.values():
            errs.update(v["err"])
        st, _ = lxplan.status(n)
        rows.append([L.NR.get(n, "?"), f"`{n}`", st, len(per)] + cells + [", ".join(f"{e} {c}" for e, c in
                                                                                    errs.most_common())])
    md.append(md_table(["nr", "name", "plan", "images"] + [SHORT[i] for i in imgs] + ["errnos (count)"], rows))
    md += ["", "## Arguments", "", "Decoded flag arguments per call, with the images using each form.", ""]
    rows = []
    for n in sorted(union, key=lambda n: L.NR.get(n, 999)):
        forms = collections.defaultdict(lambda: [0, set()])
        for i, v in ev["syscalls"][n].items():
            for k, c in v["args"].items():
                forms[k][0] += c
                forms[k][1].add(SHORT[i])
        for k, (c, users) in sorted(forms.items(), key=lambda kv: -kv[1][0]):
            rows.append([f"`{n}`", f"`{k}`", c, " ".join(sorted(users))])
    md.append(md_table(["call", "arguments", "calls", "images"], rows))
    md += ["", "## /proc, /sys, /dev and /etc", "",
           "Paths named by path arguments (numbers folded to `N`; /etc files read by one image only are in "
           "syscalls.json).", ""]
    paths = collections.defaultdict(lambda: [0, set(), set()])
    for i, ps in ev["paths"].items():
        for k, c in ps.items():
            call, path = k.split(" ", 1)
            paths[path][0] += c
            paths[path][1].add(SHORT[i])
            paths[path][2].add(call)
    rows = [[f"`{p}`", c, " ".join(sorted(u)), " ".join(sorted(calls))] for p, (c, u, calls) in sorted(paths.items())
            if not p.startswith("/etc/") or len(u) > 1]
    md.append(md_table(["path", "calls", "images", "via"], rows))
    md += ["", "## Signals delivered", ""]
    md.append(md_table(["image", "signals (count)"],
                       [[i, ", ".join(f"{k} {v}" for k, v in ev["signals"][i].items())] for i in imgs]))
    problems = plan_problems(ev)
    md += ["", "## Plan check", "", "Every call an M1 image makes is planned (M1, stub, refused with a fallback)." if
           not problems else "Calls of M1 images the plan does not cover:", ""]
    md += [f"- {p}" for p in problems]
    return "\n".join(md) + "\n", problems


def answer(name):
    """The errno a call not implemented in M1 returns there."""
    st, note = lxplan.status(name)
    m = re.search(r"\bE[A-Z0-9]{3,}\b", note)
    return m.group(0) if m else ("EPERM" if st == lxplan.REFUSED else "ENOSYS")


def render_evidence(ev):
    im = ev["images"]
    m1 = [i for i in im if im[i]["milestone"] == "M1"]
    union_m1 = {s for s, per in ev["syscalls"].items() if set(per) & set(m1)}
    allref = set().union(*(set(x["static_all"]) | set(x["static_closure"]) | set(x["inline"]) for x in im.values()))
    rows = [[f"`{x['tag']}`", x["milestone"], x["workload"], len(x["traced"]),
             len(set(x["static_closure"]) | set(x["inline"])), len(x["static_all"])] for x in im.values()]
    return "\n".join([md_table(["image", "milestone", "workload", "traced calls", "static closure",
                                "static, every object"], rows), "",
                      f"The union is {len(ev['syscalls'])} calls ({len(union_m1)} for the M1 images) against "
                      f"{len(allref)} referenced statically by the same images and {len(L.SYSCALLS)} in the x86-64 "
                      "table: dynamic use is about half of the static bound, as the literature predicts (oci.md §3)."])


def render_calls(ev):
    used = {n: sorted(per) for n, per in ev["syscalls"].items()}
    m1imgs = [i for i, x in ev["images"].items() if x["milestone"] == "M1"]
    m1used = sorted((n for n, per in used.items() if set(per) & set(m1imgs)), key=lambda n: L.NR.get(n, 999))
    must = [n for n in m1used if lxplan.status(n)[0] in (lxplan.M1, lxplan.STUB)]
    other = [f"`{n}` → {answer(n)}" for n in m1used if n not in must]
    rows, counts = [], collections.Counter()
    for nr, n in sorted(L.SYSCALLS.items()):
        st, note = lxplan.status(n)
        counts[st] += 1
        rows.append([nr, f"`{n}`", st, " ".join(SHORT[i] for i in used.get(n, [])), note])
    summary = ", ".join(f"{k} {v}" for k, v in sorted(counts.items(), key=lambda kv: -kv[1]))
    return "\n".join([f"The M1 corpus images ({', '.join(m1imgs)}) make {len(m1used)} distinct calls. M1 implements "
                      f"these {len(must)}: " + ", ".join(f"`{n}`" for n in must) + ".", "",
                      f"The other {len(other)} get an errno their callers handle: " + ", ".join(other) + ".", "",
                      f"Plan totals: {summary} ({len(L.SYSCALLS)} x86-64 calls).", "",
                      md_table(["nr", "call", "status", "traced in", "notes"], rows)])


def splice(text, block, body):
    begin, end = MARK.format("BEGIN", block), MARK.format("END", block)
    a, b = text.index(begin), text.index(end) + len(end)
    return text[:a] + begin + "\n\n" + body + "\n\n" + end + text[b:]


def outputs():
    ev = json.load(open(EVIDENCE))
    table, problems = render(ev)
    lx = splice(open(LXMD).read(), "evidence", render_evidence(ev))
    return {TABLE: table, LXMD: splice(lx, "calls", render_calls(ev))}, problems


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "collect":
        collect()
    elif cmd == "render":
        files, problems = outputs()
        for path, text in files.items():
            open(path, "w").write(text)
        for p in problems:
            print("plan:", p, file=sys.stderr)
    elif cmd == "--check":
        files, problems = outputs()
        stale = [p for p, text in files.items() if open(p).read() != text]
        for p in stale:
            print(f"table: {os.path.relpath(p, ROOT)} is not what bench/oci/table.py renders", file=sys.stderr)
        for p in problems:
            print("plan:", p, file=sys.stderr)
        sys.exit(1 if stale or problems else 0)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
